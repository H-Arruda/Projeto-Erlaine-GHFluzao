-- DED do projeto Erlaine GHFlusão (PostgreSQL)
-- Os valores de 'situacao' são provisórios até fechar os diagramas de estado.

CREATE TABLE empresa (
    id_empresa INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(100) NOT NULL,
    cnpj       CHAR(14)     NOT NULL UNIQUE,
    CONSTRAINT ck_empresa_cnpj CHECK (cnpj ~ '^[0-9]{14}$')
);

CREATE TABLE cidade (
    id_cidade INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(100) NOT NULL,
    uf        CHAR(2)      NOT NULL,
    CONSTRAINT uq_cidade_nome_uf UNIQUE (nome, uf)
);

CREATE TABLE aeroporto (
    id_aeroporto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cidade    INTEGER      NOT NULL REFERENCES cidade (id_cidade),
    nome         VARCHAR(100) NOT NULL,
    sigla        CHAR(3)      NOT NULL UNIQUE
);

CREATE TABLE voo (
    id_voo     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa INTEGER        NOT NULL REFERENCES empresa (id_empresa),
    codigo_voo VARCHAR(10)    NOT NULL UNIQUE,
    situacao   VARCHAR(20)    NOT NULL,
    valor      NUMERIC(10, 2) NOT NULL,
    CONSTRAINT ck_voo_situacao CHECK (situacao IN ('PROGRAMADO', 'EM_ANDAMENTO', 'CONCLUIDO', 'CANCELADO')),
    CONSTRAINT ck_voo_valor CHECK (valor >= 0)
);

CREATE TABLE escala (
    id_escala            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_voo               INTEGER        NOT NULL REFERENCES voo (id_voo),
    id_aeroporto_origem  INTEGER        NOT NULL REFERENCES aeroporto (id_aeroporto),
    id_aeroporto_destino INTEGER        NOT NULL REFERENCES aeroporto (id_aeroporto),
    sequencial           INTEGER        NOT NULL,
    tempo_escala         INTEGER        NOT NULL,  -- minutos
    valor                NUMERIC(10, 2) NOT NULL,
    CONSTRAINT uq_escala_voo_sequencial UNIQUE (id_voo, sequencial),
    CONSTRAINT ck_escala_origem_destino CHECK (id_aeroporto_origem <> id_aeroporto_destino),
    CONSTRAINT ck_escala_sequencial CHECK (sequencial >= 1),
    CONSTRAINT ck_escala_tempo CHECK (tempo_escala > 0),
    CONSTRAINT ck_escala_valor CHECK (valor >= 0)
);

CREATE TABLE passageiro (
    id_passageiro INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(100) NOT NULL,
    cpf           CHAR(11)     NOT NULL UNIQUE,
    CONSTRAINT ck_passageiro_cpf CHECK (cpf ~ '^[0-9]{11}$')
);

CREATE TABLE bilhete (
    id_bilhete    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_voo        INTEGER        NOT NULL REFERENCES voo (id_voo),
    id_passageiro INTEGER        NOT NULL REFERENCES passageiro (id_passageiro),
    data_emissao  TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    valor_total   NUMERIC(10, 2) NOT NULL,
    situacao      VARCHAR(20)    NOT NULL,
    CONSTRAINT ck_bilhete_situacao CHECK (situacao IN ('EMITIDO', 'UTILIZADO', 'CANCELADO')),
    CONSTRAINT ck_bilhete_valor CHECK (valor_total >= 0)
);

-- O PostgreSQL não cria índice automático nas FKs
CREATE INDEX idx_aeroporto_cidade   ON aeroporto (id_cidade);
CREATE INDEX idx_voo_empresa        ON voo (id_empresa);
CREATE INDEX idx_escala_origem      ON escala (id_aeroporto_origem);
CREATE INDEX idx_escala_destino     ON escala (id_aeroporto_destino);
CREATE INDEX idx_bilhete_voo        ON bilhete (id_voo);
CREATE INDEX idx_bilhete_passageiro ON bilhete (id_passageiro);
